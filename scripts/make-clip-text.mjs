// Text side of MobileCLIP-S0, computed once: the prompt embeddings the vision worker compares each
// frame with (src/core/clip-text.ts). Only the image encoder ships with the extension.
// Downloads the text encoder (~170 MB) and tokenizer into node_modules/.cache/mobileclip once.
// Usage: node scripts/make-clip-text.mjs
import * as ort from 'onnxruntime-node';
import { AutoTokenizer, env } from '@huggingface/transformers';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { CLIP_PROMPTS } from './clip-prompts.mjs';

const repo = 'Xenova/mobileclip_s0';
const cache = 'node_modules/.cache/mobileclip';
const dir = `${cache}/${repo}`;
mkdirSync(`${dir}/onnx`, { recursive: true });
for (const f of ['config.json', 'tokenizer.json', 'tokenizer_config.json', 'onnx/text_model.onnx']) {
  if (existsSync(`${dir}/${f}`)) continue;
  console.log('downloading', f);
  execFileSync('curl', ['-sSfL', '--retry', '4', '--retry-all-errors', '-o', `${dir}/${f}`, `https://huggingface.co/${repo}/resolve/main/${f}`], { stdio: 'inherit' });
}
env.localModelPath = cache;
env.allowRemoteModels = false;
const tok = await AutoTokenizer.from_pretrained(repo, { local_files_only: true });
const txt = await ort.InferenceSession.create(`${dir}/onnx/text_model.onnx`);

const groups = Object.entries(CLIP_PROMPTS);
const flat = groups.flatMap(([, ps]) => ps);
const ids = tok(flat, { padding: 'max_length', max_length: 77, truncation: true }).input_ids;
const out = (await txt.run({ input_ids: new ort.Tensor('int64', BigInt64Array.from(ids.data), ids.dims) })).text_embeds.data;
const D = out.length / flat.length;
const emb = new Float32Array(out.length);
for (let i = 0; i < flat.length; i++) {
  let n = 0;
  for (let k = 0; k < D; k++) n += out[i * D + k] ** 2;
  n = Math.sqrt(n);
  for (let k = 0; k < D; k++) emb[i * D + k] = out[i * D + k] / n;
}
const b64 = Buffer.from(emb.buffer).toString('base64');
const kinds = groups.flatMap(([g, ps]) => ps.map(() => g));
writeFileSync(
  'src/core/clip-text.ts',
  `// Generated by scripts/make-clip-text.mjs from scripts/clip-prompts.mjs — do not edit.\n` +
    `/** MobileCLIP-S0 text embeddings (unit length) of the prompts, ${flat.length}×${D}, float32 little-endian, base64. */\n` +
    `export const CLIP_TEXT_DIM = ${D};\n` +
    `/** Group of each prompt: W a woman / women are in the picture, M only men, N no people. */\n` +
    `export const CLIP_TEXT_KINDS = ${JSON.stringify(kinds.join(''))};\n` +
    `export const CLIP_TEXT_PROMPTS: readonly string[] = ${JSON.stringify(flat, null, 2)};\n` +
    `export const CLIP_TEXT_B64 =\n  '${b64}';\n`,
);
console.log(`src/core/clip-text.ts: ${flat.length} prompts × ${D}`);
